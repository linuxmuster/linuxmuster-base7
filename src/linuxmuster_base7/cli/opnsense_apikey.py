"""
Checks (--check) or replaces (--deploy [--force]) the API key of the firewall's root
user stored in environment.FWAPIKEYS.

Needed when the key stored on the server is no longer known to the firewall,
e.g. after the firewall was restored from an older snapshot or reinstalled
(symptom: HTTP 401 "Authentication Failed" from linuxmuster-import-subnets).
Unlike linuxmuster-opnsense-reset this touches nothing else on the firewall.

The key is generated by OPNsense itself (same code path as the web GUI's
"create API key" button) via ssh, using the server's key-based root access
that setup already configured. The old key is removed from the firewall.
"""

import base64
import configparser
import getopt
import json
import subprocess
import sys

import environment

from linuxmuster_base7.functions import FirewallAuthError, firewallApi, getSetupValue, \
    modIni, printScript

SSH_TIMEOUT = 60

# Runs on the firewall (php reads the script from stdin). Prints the new
# key and secret as one json line. @@oldkey@@ is replaced by the base64
# encoded old key to remove (may be empty; base64 is safe inside the quotes).
PHP_SCRIPT = r"""<?php
require_once 'script/load_phalcon.php';
use OPNsense\Auth\User;
use OPNsense\Core\Config;

Config::getInstance()->lock();
$mdl = new User();
$user = $mdl->getUserByName('root');
if ($user === null) {
    Config::getInstance()->unlock();
    fwrite(STDERR, "user root not found\n");
    exit(1);
}
$old = base64_decode('@@oldkey@@');
if ($old !== '') {
    $user->apikeys->del($old);
}
$new = $user->apikeys->add();
$mdl->serializeToConfig(false, true);
Config::getInstance()->save();
echo json_encode($new) . "\n";
"""


def usage():
    """Print usage information."""
    print('Usage: linuxmuster-opnsense-apikey [options]')
    print('Checks the firewall API key or deploys a new one.')
    print(' [options] may be:')
    print(' -c, --check  : Only check if the current API key still works')
    print('                (exit code 0 = works, 1 = does not work).')
    print(' -d, --deploy : Deploy a new API key to the firewall and store it on the server.')
    print('                Skipped if the current key still works, unless --force is given.')
    print(' -f, --force  : Together with --deploy: replace the key even if it still works.')
    print(' -h, --help   : Print this help.')


def readOldKey():
    """Return the key currently stored in FWAPIKEYS, or '' if there is none."""
    cfg = configparser.RawConfigParser(delimiters=('=',))
    cfg.read(environment.FWAPIKEYS)
    return cfg.get('api', 'key', fallback='')


def currentKeyWorks():
    """Check whether the stored credentials are accepted by the firewall."""
    try:
        return firewallApi('get', '/core/firmware/status', retries=1) is not None
    except Exception:
        # missing/unreadable ini or rejected credentials: key is not usable
        return False


def createKeyOnFirewall(firewallip, old_key):
    """Create a new API key for root on the firewall via ssh.

    Returns:
        Tuple (key, secret), or None on failure
    """
    old_b64 = base64.b64encode(old_key.encode()).decode() if old_key else ''
    cmd = ['ssh', '-q', '-oBatchMode=yes', '-oStrictHostKeyChecking=no', '-l', 'root',
           firewallip, 'php']
    script = PHP_SCRIPT.replace('@@oldkey@@', old_b64)
    try:
        res = subprocess.run(cmd, input=script, capture_output=True, text=True,
                             timeout=SSH_TIMEOUT, check=False)
    except subprocess.TimeoutExpired:
        printScript('* ssh to firewall timed out.')
        return None
    if res.returncode != 0:
        printScript(f'* Creating the key failed: {res.stderr.strip() or res.stdout.strip()}')
        return None
    try:
        data = json.loads(res.stdout.strip().splitlines()[-1])
        return data['key'], data['secret']
    except (IndexError, KeyError, ValueError):
        printScript(f'* Unexpected response from firewall: {res.stdout.strip()}')
        return None


def main():
    """Entry point of linuxmuster-opnsense-apikey."""
    try:
        opts, _ = getopt.getopt(sys.argv[1:], 'cdfh', ['check', 'deploy', 'force', 'help'])
    except getopt.GetoptError as err:
        print(err)
        usage()
        sys.exit(2)
    check = False
    deploy = False
    force = False
    for o, _ in opts:
        if o in ('-c', '--check'):
            check = True
        elif o in ('-d', '--deploy'):
            deploy = True
        elif o in ('-f', '--force'):
            force = True
        elif o in ('-h', '--help'):
            usage()
            sys.exit(0)
    # without an action show the help
    if not (check or deploy):
        usage()
        sys.exit(0)
    if check and deploy:
        print('Options --check and --deploy are mutually exclusive.')
        usage()
        sys.exit(2)
    if force and not deploy:
        print('Option --force only works together with --deploy.')
        usage()
        sys.exit(2)

    printScript('linuxmuster-opnsense-apikey')
    if getSetupValue('skipfw'):
        printScript('Firewall is skipped by setup!')
        sys.exit(0)

    if check:
        if currentKeyWorks():
            printScript('* The current API key works.')
            sys.exit(0)
        printScript('* The current API key does not work.')
        printScript('* Run linuxmuster-opnsense-apikey --deploy to deploy a new one.')
        sys.exit(1)

    if not force and currentKeyWorks():
        printScript('* The current API key works, nothing deployed.')
        printScript('* Use --deploy --force to replace it anyway.')
        sys.exit(0)

    firewallip = getSetupValue('firewallip')
    printScript('* Creating new API key on firewall ' + firewallip)
    created = createKeyOnFirewall(firewallip, readOldKey())
    if created is None:
        printScript('* Is root ssh access from this server to the firewall working?')
        sys.exit(1)
    key, secret = created

    # key first, then secret - same order as setup's saveApiCredentials()
    if not (modIni(environment.FWAPIKEYS, 'api', 'key', key, mode=0o400)
            and modIni(environment.FWAPIKEYS, 'api', 'secret', secret)):
        printScript(f'* Failed to write {environment.FWAPIKEYS}!')
        sys.exit(1)
    printScript(f'* New credentials saved to {environment.FWAPIKEYS}.')

    if currentKeyWorks():
        printScript('* Firewall API accepts the new key.')
    else:
        printScript('* Warning: firewall API does not accept the new key yet.')
        sys.exit(1)


if __name__ == '__main__':
    main()
